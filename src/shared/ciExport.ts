import type { Scenario } from './types'

/** Generate a Playwright-style sketch from a Katch scenario. */
export function scenarioToPlaywright(scenario: Scenario): string {
  const lines: string[] = [
    `import { test, expect } from '@playwright/test'`,
    ``,
    `// Generated by Katch! — review before CI use`,
    `test(${JSON.stringify(scenario.name)}, async ({ page }) => {`,
  ]
  if (scenario.origin) {
    lines.push(`  await page.goto(${JSON.stringify(scenario.origin)})`)
  }
  for (const step of scenario.steps) {
    if (step.kind === 'inject' && step.selector) {
      lines.push(
        `  await page.locator(${JSON.stringify(step.selector)}).fill(${JSON.stringify(step.payload ?? '')})`,
      )
    } else if (step.kind === 'click' && step.selector) {
      lines.push(`  await page.locator(${JSON.stringify(step.selector)}).click()`)
    } else if (step.kind === 'wait') {
      lines.push(`  await page.waitForTimeout(${step.waitMs ?? 500})`)
    } else if (step.kind === 'assert' && step.assertKind === 'urlIncludes') {
      lines.push(
        `  await expect(page).toHaveURL(/${escapeRegExp(step.assertValue ?? '')}/)`,
      )
    }
  }
  lines.push(`})`, ``)
  return lines.join('\n')
}

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

export function scenarioToCypress(scenario: Scenario): string {
  const lines: string[] = [
    `// Generated by Katch! — review before CI use`,
    `describe(${JSON.stringify(scenario.name)}, () => {`,
    `  it('runs scenario', () => {`,
  ]
  if (scenario.origin) {
    lines.push(`    cy.visit(${JSON.stringify(scenario.origin)})`)
  }
  for (const step of scenario.steps) {
    if (step.kind === 'inject' && step.selector) {
      lines.push(
        `    cy.get(${JSON.stringify(step.selector)}).clear().type(${JSON.stringify(step.payload ?? '')})`,
      )
    } else if (step.kind === 'click' && step.selector) {
      lines.push(`    cy.get(${JSON.stringify(step.selector)}).click()`)
    } else if (step.kind === 'wait') {
      lines.push(`    cy.wait(${step.waitMs ?? 500})`)
    } else if (step.kind === 'assert' && step.assertKind === 'urlIncludes') {
      lines.push(`    cy.url().should('include', ${JSON.stringify(step.assertValue ?? '')})`)
    }
  }
  lines.push(`  })`, `})`, ``)
  return lines.join('\n')
}
